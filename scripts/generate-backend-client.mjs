#!/usr/bin/env node
/**
 * Generate typed route manifest and workflow exports from backend contract bundle.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const contractDir = join(root, 'src/api/backend-contract')
const generatedDir = join(root, 'src/api/generated')

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function toPathBuilder(pathTemplate) {
  const params = [...pathTemplate.matchAll(/\{([^}]+)\}/g)].map((m) => m[1])
  if (params.length === 0) {
    return `() => '${pathTemplate}'`
  }
  const args = params.map((p) => `${p}: string`).join(', ')
  let expr = pathTemplate
  for (const p of params) {
    expr = expr.replaceAll(`{${p}}`, '${encodeURIComponent(' + p + ')}')
  }
  return `(${args}) => \`${expr}\``
}

function main() {
  const routeManifest = readJson(join(contractDir, 'route-manifest.json'))
  const workflow = readJson(join(contractDir, 'workflow-contract.json'))
  const contractManifest = readJson(join(contractDir, 'contract-manifest.json'))

  mkdirSync(generatedDir, { recursive: true })

  const operations = routeManifest.operations
  const operationIds = operations.map((op) => op.operationId)

  const routesTs = `/**
 * AUTO-GENERATED by scripts/generate-backend-client.mjs — DO NOT EDIT
 * Contract version: ${routeManifest.version}
 */
export const GENERATED_CONTRACT_VERSION = '${routeManifest.version}' as const

export type HttpMethod = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE'

export type OperationId =
${operationIds.map((id) => `  | '${id}'`).join('\n')}

export type BackendOperation = {
  operationId: OperationId
  method: HttpMethod
  pathTemplate: string
  featureArea: string
  source: string
  successStatus: number
  responseSchema?: string
  requestBodySchema?: string
}

export const backendOperations: Record<OperationId, BackendOperation> = {
${operations
  .map(
    (op) => `  ${op.operationId}: {
    operationId: '${op.operationId}',
    method: '${op.method}',
    pathTemplate: '${op.path}',
    featureArea: '${op.featureArea}',
    source: '${op.source}',
    successStatus: ${op.successStatus},
    responseSchema: ${op.responseSchema ? `'${op.responseSchema}'` : 'undefined'},
    requestBodySchema: ${op.requestBodySchema ? `'${op.requestBodySchema}'` : 'undefined'},
  },`,
  )
  .join('\n')}
}

export const backendRoutes = {
${operations
  .map((op) => {
    const builder = toPathBuilder(op.path)
    return `  ${op.operationId}: ${builder},`
  })
  .join('\n')}
} as const

export function getOperation(id: OperationId): BackendOperation {
  return backendOperations[id]
}

export function listOperationIds(): OperationId[] {
  return Object.keys(backendOperations) as OperationId[]
}

export const OPERATION_COUNT = ${operations.length} as const
export const ROUTE_COUNT = ${routeManifest.routeCount} as const
`

  const workflowTs = `/**
 * AUTO-GENERATED by scripts/generate-backend-client.mjs — DO NOT EDIT
 */
export const WORKFLOW_CONTRACT_VERSION = '${workflow.version}' as const

export const SPRINT1_STAGES = ${JSON.stringify(workflow.sprint1.stages, null, 2)} as const
export type Sprint1Stage = (typeof SPRINT1_STAGES)[number]

export const SPRINT1_ACTIONS = ${JSON.stringify(workflow.sprint1.actions, null, 2)} as const
export type Sprint1Action = (typeof SPRINT1_ACTIONS)[number]

export const SPRINT2_SESSION_STATUSES = ${JSON.stringify(workflow.sprint2.sessionStatuses, null, 2)} as const
export const SPRINT2_SESSION_STAGES = ${JSON.stringify(workflow.sprint2.sessionStages, null, 2)} as const
export const SPRINT2_NEXT_ACTIONS = ${JSON.stringify(workflow.sprint2.nextActions, null, 2)} as const
export type Sprint2NextAction = (typeof SPRINT2_NEXT_ACTIONS)[number]
export const SPRINT2_MUTATION_ACTIONS = ${JSON.stringify(workflow.sprint2.mutationActions, null, 2)} as const
export type Sprint2MutationAction = (typeof SPRINT2_MUTATION_ACTIONS)[number]
`

  const typesTs = `/**
 * AUTO-GENERATED by scripts/generate-backend-client.mjs — DO NOT EDIT
 * Wire types are derived from backend JSON schemas; use adapters for UI models.
 */
export type { OperationId, BackendOperation, HttpMethod } from '@/api/generated/backend-routes'
export { GENERATED_CONTRACT_VERSION, OPERATION_COUNT, ROUTE_COUNT } from '@/api/generated/backend-routes'
`

  const fingerprint = createHash('sha256')
    .update(routesTs)
    .update(workflowTs)
    .digest('hex')

  const stampTs = `/**
 * AUTO-GENERATED by scripts/generate-backend-client.mjs — DO NOT EDIT
 */
export const GENERATED_FINGERPRINT = '${fingerprint}' as const
export const GENERATED_AT = '${new Date().toISOString()}' as const
export const SOURCE_CONTRACT_VERSION = '${contractManifest.version}' as const
`

  writeFileSync(join(generatedDir, 'backend-routes.ts'), routesTs)
  writeFileSync(join(generatedDir, 'backend-workflow.ts'), workflowTs)
  writeFileSync(join(generatedDir, 'backend-types.ts'), typesTs)
  writeFileSync(join(generatedDir, 'generated-stamp.ts'), stampTs)

  console.log(
    `Generated ${operations.length} operations (${routeManifest.routeCount} routes) for contract ${routeManifest.version}`,
  )
}

main()
